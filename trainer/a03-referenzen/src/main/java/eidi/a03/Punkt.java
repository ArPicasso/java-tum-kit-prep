package eidi.a03;

// Diese Klasse ist fertig. Bitte nicht verändern.
public class Punkt {

    public int x;
    public int y;

    public Punkt(int x, int y) {
        this.x = x;
        this.y = y;
    }

    @Override
    public String toString() {
        return "(" + x + ", " + y + ")";
    }
}
